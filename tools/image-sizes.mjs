import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, relative } from 'node:path';
import { imageSize } from 'image-size';
const root = resolve(import.meta.dirname, '..');
const sizes = {};
async function walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = resolve(dir, entry.name);
    if (entry.isDirectory()) await walk(path);
    else if (/\.(webp|png|jpe?g|avif)$/i.test(entry.name)) {
      const { width, height } = imageSize(await readFile(path));
      sizes['/' + relative(resolve(root, 'public'), path).replaceAll('\\', '/')] = [width, height];
    }
  }
}
await walk(resolve(root, 'public'));
const helpers = await readFile(resolve(root, 'tools/image-helpers.txt'), 'utf8');
await writeFile(resolve(root, 'src/imageSizes.js'), `// Generated by npm run images:sizes from the real source files.\nexport const IMAGE_SIZES = ${JSON.stringify(sizes)};\n\n${helpers}`);
console.log(`${Object.keys(sizes).length} image dimensions recorded.`);
